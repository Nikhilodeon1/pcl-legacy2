"""Collect every number the paper may quote from the revision outputs into results/revision/numbers.json."""
import csv
import json
import os

import revlib as R

REV = R.REV
J = lambda f: json.load(open(os.path.join(REV, f))) if os.path.exists(os.path.join(REV, f)) else None
out = {"_note": "generated by make_numbers.py; local caches are 25% stay subsamples for MIMIC/eICU unless stated; fixed-T and mortality-audit entries are absent until the pod runs"}

g1 = J("g1_probe.json")
if g1:
    out["g1_probe"] = {"flag_los": g1["flag_los"], "flag_mortality": g1["flag_mortality"], "thresholds": g1["thresholds"],
                       "rows": g1["probe_rows"], "mask_los_link": g1["mask_los_link"]}
a1 = J("a1_verdicts.json")
if a1:
    out["a1_verdicts"] = a1
out["a3_bootstrap_los_mean_over_seeds"] = []
p = os.path.join(REV, "a3_bootstrap_los.csv")
if os.path.exists(p):
    for r in csv.DictReader(open(p)):
        if r["scope"] == "mean_over_seeds" and r["metric"] == "r2":
            out["a3_bootstrap_los_mean_over_seeds"].append({k: r[k] for k in ("target", "quantity", "point", "ci_lo", "ci_hi", "note")})
for name, f in (("a4_selection_los", "a4_selection_los.json"), ("a5_indomain", "a5_indomain.json"), ("a6_pooling_null", "a6_pooling_null.json"),
                ("g2_cohort", "g2_cohort.json"), ("g3_numbers", "g3_numbers.json"), ("g3b_text_claims", "g3b_text_claims.json")):
    v = J(f)
    if v is not None:
        out[name] = v
# replicate-noise yardstick: ERM and DRO are the same recipe, so |ERM-DRO| is pretraining-replicate noise (n=1 pair)
rows = out["a3_bootstrap_los_mean_over_seeds"]
get = lambda t, q: next((float(r["point"]) for r in rows if r["target"] == t and r["quantity"] == q), None)
out["replicate_noise_yardstick_los"] = {t: dict(erm_minus_dro=get(t, "erm-dro"), pcl_minus_dro=get(t, "pcl-dro"), pcl_minus_erm=get(t, "pcl-erm")) for t in ("pn_b", "mimic", "eicu")}
json.dump(out, open(os.path.join(REV, "numbers.json"), "w"), indent=1, default=float)
print("numbers.json keys:", list(out))
